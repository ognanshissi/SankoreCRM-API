namespace Sankore.Modules.Leads.Infrastructure.Configurations;

using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Sankore.Modules.Leads.Domain;
using Sankore.Shared.Infrastructure.Crypto;
using Sankore.Shared.Infrastructure.Persistence;

/// <param name="encryptor">
/// M13's keyed encryptor, for the member's birth date and address. Applied by hand from
/// <see cref="LeadsDbContext"/> and excluded from the assembly scan, like
/// <see cref="LeadConfiguration"/> — a scanned configuration cannot receive a dependency.
/// </param>
internal sealed class LeadHouseholdMemberConfiguration(IFieldEncryptor encryptor)
    : IEntityTypeConfiguration<LeadHouseholdMember>
{
    /// <summary>
    /// At most ONE ACTIVE spouse per lead — the database half of the invariant BNF-B-03 asks to be
    /// enforced twice. The aggregate's check gives an actionable error code; this is what holds
    /// when two requests add a spouse at the same instant, which no in-memory check can.
    /// </summary>
    internal const string OneSpouseIndex = "uq_lead_one_spouse";

    public void Configure(EntityTypeBuilder<LeadHouseholdMember> builder)
    {
        builder.ToTable("lead_household_members", t =>
        {
            // The pairing of type and union type, as a CHECK. The aggregate refuses both halves
            // already; this catches a row arriving any other way — a future import, a manual fix.
            t.HasCheckConstraint(
                "ck_lhm_union",
                "(type = 'Spouse') = (spouse_union_type IS NOT NULL)");
        });

        builder.HasKey(m => m.Id);

        // ValueGeneratedNever, and this is NOT cosmetic.
        //
        // EF treats a Guid key as store-generated by default, so an entity whose key is already
        // set is assumed to EXIST — and a member appended to a loaded Lead.HouseholdMembers is
        // tracked as Modified rather than Added. SaveChanges then tries to UPDATE a row that was
        // never inserted: "Attempted to update or delete an entity that does not exist in the
        // store". The application supplies this key in LeadHouseholdMember.Create, so EF has to be
        // told.
        //
        // Measured: the Lot 3 tests all added members to a lead that was itself new, where the
        // whole graph is Added and the state is inherited. Only the load-modify-save path the
        // AddHouseholdMember endpoint actually uses exposes it.
        builder.Property(m => m.Id).ValueGeneratedNever();

        builder.Property(m => m.Type).HasConversion<string>().HasMaxLength(10).IsRequired();
        builder.Property(m => m.SpouseUnionType).HasConversion<string>().HasMaxLength(15);
        builder.Property(m => m.UsesPrincipalAddress).HasDefaultValue(false).IsRequired();
        builder.Property(m => m.RemovalReason).HasMaxLength(500);

        // PersonIdentity and PepStatus through the SHARED mapping, with M13's own key — one column
        // list for every module that stores a person, so a conversion snapshot lines up field for
        // field. See PersonMapping.
        builder.OwnsPersonIdentity(m => m.Identity, encryptor);
        builder.OwnsPepStatus(m => m.Pep);

        // Null = never asked. See LeadHouseholdMember.PepDeclaredAt.
        builder.Property(m => m.PepDeclaredAt);

        builder.HasIndex(m => new { m.TenantId, m.LeadId });

        builder.HasIndex(m => m.LeadId)
               .IsUnique()
               .HasDatabaseName(OneSpouseIndex)
               .HasFilter("type = 'Spouse' AND removed_at IS NULL");
    }
}
