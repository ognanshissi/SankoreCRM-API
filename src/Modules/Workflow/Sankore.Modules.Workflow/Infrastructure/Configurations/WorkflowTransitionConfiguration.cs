using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;
using Sankore.Modules.Workflow.Domain;

namespace Sankore.Modules.Workflow.Infrastructure.Configurations;

internal sealed class WorkflowTransitionConfiguration : IEntityTypeConfiguration<WorkflowTransition>
{
    public void Configure(EntityTypeBuilder<WorkflowTransition> b)
    {
        b.ToTable("workflow_transitions");
        b.HasKey(t => t.Id);

        b.Property(t => t.EventCode).HasMaxLength(50).IsRequired();
        b.Property(t => t.ToTerminalStatus).HasConversion<string>().HasMaxLength(50);
        b.Property(t => t.ConditionJson).HasColumnType("text");
        b.Property(t => t.IsAutoGenerated).HasDefaultValue(false).ValueGeneratedNever();

        b.HasIndex(t => new { t.TemplateId, t.FromStateId, t.EventCode, t.Priority });
    }
}
