using Sankore.Modules.Workflow.Domain.Events;
using Sankore.Shared.Kernel;

namespace Sankore.Modules.Workflow.Domain;

/// <summary>
/// Defines the approval circuit for a given entity type within a tenant.
/// A tenant can have at most one active template per EntityType.
/// </summary>
public sealed class WorkflowTemplate : AggregateRoot
{
    public Guid Id { get; private set; }

    /// <summary>Entity type this template applies to (e.g. "Lead", "Opportunity").</summary>
    public string EntityType { get; private set; } = string.Empty;

    public string Name { get; private set; } = string.Empty;
    public string? Description { get; private set; }

    /// <summary>
    /// Which circuit of <see cref="EntityType"/> this template versions — empty for the single
    /// circuit every entity type had until projects needed several (product owner, 2026-10-24: a
    /// credit committee and a group-insurance committee are two circuits of the same project type).
    /// Stable across versions — a project step names its circuit, never a template id, so
    /// publishing version 2 does not break the link. Uniqueness (one version-1, one draft, one
    /// active) is per (entity type, circuit).
    /// </summary>
    public string Circuit { get; private set; } = string.Empty;

    /// <summary>The entity type whose templates are separate circuits, one per name.</summary>
    public const string ProjectEntityType = "Opportunity";
    public const int MaxCircuitLength = 60;
    public bool IsActive { get; private set; }

    /// <summary>
    /// Monotonically increasing version number. Version 1 = original template.
    /// New versions are created via <see cref="CreateDraft"/> without touching the active one.
    /// </summary>
    public int Version { get; private set; } = 1;

    public DateTimeOffset CreatedAt { get; private set; }
    public DateTimeOffset UpdatedAt { get; private set; }
    public Guid CreatedByUserId { get; private set; }

    private readonly List<WorkflowStepDefinition> _steps = [];
    public IReadOnlyCollection<WorkflowStepDefinition> Steps => _steps.AsReadOnly();

    private readonly List<WorkflowTransition> _transitions = [];
    public IReadOnlyCollection<WorkflowTransition> Transitions => _transitions.AsReadOnly();

    private WorkflowTemplate() { }

    public static WorkflowTemplate Create(
        Guid tenantId,
        string entityType,
        string name,
        Guid createdByUserId,
        string? description = null,
        string? circuit = null)
    {
        if (string.IsNullOrWhiteSpace(entityType))
            throw new DomainException("EntityType is required.");
        if (circuit?.Length > MaxCircuitLength)
            throw new DomainException("Circuit key is too long.");
        if (string.IsNullOrWhiteSpace(name))
            throw new DomainException("Template name is required.");

        var now = DateTimeOffset.UtcNow;
        return new WorkflowTemplate
        {
            Id = Guid.NewGuid(),
            TenantId = tenantId,
            EntityType = entityType.Trim(),
            Circuit = circuit?.Trim() ?? string.Empty,
            Name = name.Trim(),
            Description = description?.Trim(),
            IsActive = false,
            Version = 1,
            CreatedAt = now,
            UpdatedAt = now,
            CreatedByUserId = createdByUserId
        };
    }

    public void Update(string name, string? description)
    {
        if (string.IsNullOrWhiteSpace(name))
            throw new DomainException("Template name is required.");

        Name = name.Trim();
        Description = description?.Trim();
        UpdatedAt = DateTimeOffset.UtcNow;
    }

    public void Activate()
    {
        if (_steps.Count == 0)
            throw new DomainException("Cannot activate a template with no steps.");

        // Rebuild the AUTO-GENERATED transitions from the current step arrangement, and only
        // those. Custom transitions are the tenant's own routing — AddTransition's contract, the
        // refusal in RemoveTransition and CreateDraft's cloning all say they outlive an
        // activation, so a Clear() here would contradict the rest of this aggregate. It did not
        // show in practice only because ActivateTemplateHandler never loads the Transitions
        // navigation, which made the Clear() a no-op on an empty list.
        _transitions.RemoveAll(t => t.IsAutoGenerated);

        var sorted = _steps.OrderBy(s => s.Order).ToList();
        for (var i = 0; i < sorted.Count; i++)
        {
            var cur    = sorted[i];
            bool isLast = i == sorted.Count - 1;

            // APPROVE → advance to next step, or complete the workflow.
            // Priority 100 makes these the fallback; custom conditional transitions
            // added via AddTransition() at lower priority values take precedence.
            _transitions.Add(WorkflowTransition.Create(
                Id, cur.Id,
                toStateId:        isLast ? null : sorted[i + 1].Id,
                EventCodes.Approve,
                toTerminalStatus: isLast ? WorkflowStatus.Completed : null,
                priority:         100,
                isAutoGenerated:  true));

            // REJECT → rejected terminal (applies at any step)
            _transitions.Add(WorkflowTransition.Create(
                Id, cur.Id, toStateId: null,
                EventCodes.Reject,
                toTerminalStatus: WorkflowStatus.Rejected,
                priority:         100,
                isAutoGenerated:  true));
        }

        IsActive = true;
        UpdatedAt = DateTimeOffset.UtcNow;
    }

    public void Deactivate()
    {
        IsActive = false;
        UpdatedAt = DateTimeOffset.UtcNow;
    }

    public WorkflowStepDefinition AddStep(
        int order,
        string name,
        string? description = null,
        string? approverRoleCode = null,
        int? timeoutHours = null,
        StepKind kind = StepKind.Validation,
        string? configJson = null,
        bool isBlocking = false)
    {
        if (_steps.Any(s => s.Order == order))
            throw new DomainException($"A step with order {order} already exists.");

        var step = WorkflowStepDefinition.Create(
            Id, order, name, description, approverRoleCode, timeoutHours, kind, configJson, isBlocking);
        _steps.Add(step);
        UpdatedAt = DateTimeOffset.UtcNow;
        return step;
    }

    /// <summary>
    /// Libère la position <paramref name="order"/> en décalant d'un rang toutes les étapes qui
    /// l'occupent ou la suivent, pour y insérer une étape au milieu du parcours.
    ///
    /// Le décalage passe par une plage temporaire (<paramref name="parkingOffset"/>) : l'index
    /// unique (TemplateId, Order) est vérifié à chaque UPDATE par PostgreSQL, et passer 3→4 alors que
    /// 4 existe encore le violerait. L'appelant enregistre une première fois après
    /// <see cref="ParkStepsFrom"/>, puis appelle <see cref="UnparkSteps"/>.
    /// </summary>
    public IReadOnlyList<WorkflowStepDefinition> ParkStepsFrom(int order, int parkingOffset = 10_000)
    {
        var moved = _steps.Where(s => s.Order >= order).ToList();
        foreach (var step in moved) step.MoveTo(step.Order + parkingOffset);
        return moved;
    }

    public void UnparkSteps(IEnumerable<WorkflowStepDefinition> parked, int parkingOffset = 10_000)
    {
        foreach (var step in parked) step.MoveTo(step.Order - parkingOffset + 1);
        UpdatedAt = DateTimeOffset.UtcNow;
    }

    /// <summary>
    /// Adds a custom (non-auto-generated) transition to this template.
    /// Custom transitions default to priority 0, which is lower than the auto-generated
    /// fallbacks (priority 100), so they are evaluated first.
    /// Use <paramref name="conditionJson"/> to limit when the transition fires.
    /// </summary>
    public WorkflowTransition AddTransition(
        Guid fromStateId,
        Guid? toStateId,
        string eventCode,
        WorkflowStatus? toTerminalStatus = null,
        string? conditionJson = null,
        int priority = 0)
    {
        if (_steps.All(s => s.Id != fromStateId))
            throw new DomainException("FromState step not found in this template.");
        if (toStateId.HasValue && _steps.All(s => s.Id != toStateId.Value))
            throw new DomainException("ToState step not found in this template.");
        if (string.IsNullOrWhiteSpace(eventCode))
            throw new DomainException("EventCode is required.");

        var transition = WorkflowTransition.Create(
            Id, fromStateId, toStateId, eventCode,
            toTerminalStatus, conditionJson, priority, isAutoGenerated: false);
        _transitions.Add(transition);
        UpdatedAt = DateTimeOffset.UtcNow;
        return transition;
    }

    /// <summary>Removes a custom transition. Auto-generated transitions cannot be removed directly.</summary>
    public void RemoveTransition(Guid transitionId)
    {
        var transition = _transitions.FirstOrDefault(t => t.Id == transitionId)
            ?? throw new DomainException("Transition not found.");
        if (transition.IsAutoGenerated)
            throw new DomainException(
                "Auto-generated transitions cannot be removed directly. " +
                "Deactivate and re-activate the template to rebuild them.");
        _transitions.Remove(transition);
        UpdatedAt = DateTimeOffset.UtcNow;
    }

    /// <summary>
    /// Creates a new inactive draft of this template at <see cref="Version"/> + 1,
    /// cloning all steps, their rules, and custom (non-auto-generated) transitions.
    /// The caller is responsible for persisting the returned template and all its children.
    /// Auto-generated transitions are NOT cloned — they will be rebuilt when the draft is activated.
    /// </summary>
    public WorkflowTemplate CreateDraft(Guid createdByUserId)
    {
        var now = DateTimeOffset.UtcNow;
        var draft = new WorkflowTemplate
        {
            Id              = Guid.NewGuid(),
            TenantId        = TenantId,
            EntityType      = EntityType,
            Circuit         = Circuit,
            Name            = Name,
            Description     = Description,
            IsActive        = false,
            Version         = Version + 1,
            CreatedAt       = now,
            UpdatedAt       = now,
            CreatedByUserId = createdByUserId
        };

        // Clone steps, building old→new Id map for transition remapping.
        var stepIdMap = new Dictionary<Guid, Guid>();
        foreach (var step in _steps.OrderBy(s => s.Order))
        {
            var newStep = WorkflowStepDefinition.Create(
                draft.Id, step.Order, step.Name, step.Description,
                step.ApproverRoleCode, step.TimeoutHours,
                step.Kind, step.ConfigJson, step.IsBlocking);

            stepIdMap[step.Id] = newStep.Id;

            foreach (var rule in step.Rules)
                newStep.AddRule(rule.RuleType, rule.Field, rule.Operator, rule.Value, rule.LogicalGroup);

            draft._steps.Add(newStep);
        }

        // Clone custom transitions only — auto-generated are rebuilt on Activate().
        foreach (var t in _transitions.Where(t => !t.IsAutoGenerated))
        {
            if (!stepIdMap.TryGetValue(t.FromStateId, out var newFrom))
                continue;

            Guid? newTo = t.ToStateId.HasValue && stepIdMap.TryGetValue(t.ToStateId.Value, out var mapped)
                ? mapped : null;

            draft._transitions.Add(WorkflowTransition.Create(
                draft.Id, newFrom, newTo, t.EventCode,
                t.ToTerminalStatus, t.ConditionJson, t.Priority, isAutoGenerated: false));
        }

        return draft;
    }

    public void RemoveStep(Guid stepId)
    {
        var step = _steps.FirstOrDefault(s => s.Id == stepId)
            ?? throw new DomainException("Step not found.");
        _steps.Remove(step);
        // Remove all transitions referencing the deleted step
        _transitions.RemoveAll(t => t.FromStateId == stepId || t.ToStateId == stepId);
        UpdatedAt = DateTimeOffset.UtcNow;
    }

    /// <summary>
    /// The circuit key a NEW project template gets from its name (« Comité crédit PME » →
    /// « comite-credit-pme »); other entity types keep the single empty circuit.
    /// </summary>
    public static string CircuitFor(string entityType, string name)
    {
        if (entityType.Trim() != ProjectEntityType)
            return string.Empty;

        var normalized = name.Trim().Normalize(System.Text.NormalizationForm.FormD);
        var sb = new System.Text.StringBuilder();
        foreach (var c in normalized)
        {
            if (System.Globalization.CharUnicodeInfo.GetUnicodeCategory(c) == System.Globalization.UnicodeCategory.NonSpacingMark)
                continue;
            sb.Append(char.IsLetterOrDigit(c) ? char.ToLowerInvariant(c) : '-');
        }

        var slug = System.Text.RegularExpressions.Regex.Replace(sb.ToString(), "-{2,}", "-").Trim('-');
        if (slug.Length == 0) slug = "circuit";
        return slug.Length <= MaxCircuitLength ? slug : slug[..MaxCircuitLength].TrimEnd('-');
    }
}
