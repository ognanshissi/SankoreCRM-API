namespace Sankore.Modules.Workflow.Tests.Domain;

using FluentAssertions;
using Sankore.Modules.Workflow.Domain;
using Sankore.Shared.Kernel;
using Xunit;

public sealed class WorkflowTemplateTests
{
    private static readonly Guid _tenantId = Guid.NewGuid();
    private static readonly Guid _userId = Guid.NewGuid();

    private static WorkflowTemplate MakeTemplate(string entityType = "Lead") =>
        WorkflowTemplate.Create(_tenantId, entityType, "Approval circuit", _userId);

    // ── S1: Create sets properties correctly ──────────────────────────────

    [Fact]
    public void Create_sets_properties_and_is_inactive()
    {
        var t = MakeTemplate();

        t.EntityType.Should().Be("Lead");
        t.Name.Should().Be("Approval circuit");
        t.IsActive.Should().BeFalse();
        t.TenantId.Should().Be(_tenantId);
        t.Steps.Should().BeEmpty();
    }

    // ── S2: Activate requires at least one step ───────────────────────────

    [Fact]
    public void Cannot_activate_template_without_steps()
    {
        var t = MakeTemplate();
        var act = () => t.Activate();
        act.Should().Throw<DomainException>().WithMessage("*no steps*");
    }

    // ── S3: AddStep + Activate happy path ─────────────────────────────────

    [Fact]
    public void Activate_succeeds_when_template_has_steps()
    {
        var t = MakeTemplate();
        t.AddStep(1, "Manager approval", approverRoleCode: "branchmanager");

        t.Activate();

        t.IsActive.Should().BeTrue();
        t.Steps.Should().ContainSingle(s => s.Name == "Manager approval");
    }

    // ── S3b: Activate rebuilds only the auto-generated transitions ────────

    [Fact]
    public void Activate_regenerates_the_auto_transitions_from_the_steps()
    {
        var t = MakeTemplate();
        var first = t.AddStep(1, "Agent");
        var last = t.AddStep(2, "Manager");

        t.Activate();

        // One APPROVE and one REJECT per step, all at the fallback priority.
        t.Transitions.Should().HaveCount(4);
        t.Transitions.Should().OnlyContain(x => x.IsAutoGenerated && x.Priority == 100);

        // The APPROVE chain walks the steps in order and completes on the last one.
        t.Transitions.Should().ContainSingle(x =>
            x.FromStateId == first.Id && x.EventCode == EventCodes.Approve
            && x.ToStateId == last.Id && x.ToTerminalStatus == null);
        t.Transitions.Should().ContainSingle(x =>
            x.FromStateId == last.Id && x.EventCode == EventCodes.Approve
            && x.ToStateId == null && x.ToTerminalStatus == WorkflowStatus.Completed);
    }

    [Fact]
    public void Activate_keeps_custom_transitions()
    {
        var t = MakeTemplate();
        var step = t.AddStep(1, "Agent");
        var custom = t.AddTransition(
            step.Id, toStateId: null, eventCode: "ESCALATE",
            toTerminalStatus: WorkflowStatus.Cancelled, priority: 10);

        t.Activate();

        // A custom route is the tenant's own routing, not something activation owns. Before this
        // was RemoveAll(IsAutoGenerated) the method cleared the whole list, so publishing a
        // template would have dropped every hand-built transition — invisibly, because the
        // handler never loads the navigation.
        t.Transitions.Should().Contain(x => x.Id == custom.Id);
        t.Transitions.Count(x => x.IsAutoGenerated).Should().Be(2);
    }

    [Fact]
    public void Re_activating_does_not_duplicate_the_auto_transitions()
    {
        var t = MakeTemplate();
        t.AddStep(1, "Agent");

        t.Activate();
        var firstGeneration = t.Transitions.Select(x => x.Id).ToArray();

        t.Deactivate();
        t.Activate();

        // Superseded, not accumulated: two APPROVE routes out of one step would make the engine's
        // choice depend on row order.
        t.Transitions.Should().HaveCount(2);
        t.Transitions.Select(x => x.Id).Should().NotIntersectWith(firstGeneration);
    }

    // ── S4: Duplicate order rejected ──────────────────────────────────────

    [Fact]
    public void AddStep_rejects_duplicate_order()
    {
        var t = MakeTemplate();
        t.AddStep(1, "Step A");

        var act = () => t.AddStep(1, "Step B");
        act.Should().Throw<DomainException>().WithMessage("*order 1*");
    }

    // ── S5: RemoveStep removes the step ───────────────────────────────────

    [Fact]
    public void RemoveStep_removes_the_step()
    {
        var t = MakeTemplate();
        var step = t.AddStep(1, "Step A");

        t.RemoveStep(step.Id);

        t.Steps.Should().BeEmpty();
    }
}
