namespace Sankore.Modules.Integration.Features.Messaging.Webhook;

using System.Security.Cryptography;
using System.Text;
using Hangfire;
using Microsoft.AspNetCore.Builder;
using Microsoft.AspNetCore.Http;
using Microsoft.AspNetCore.Routing;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;
using Sankore.Modules.Integration.Domain;
using Sankore.Modules.Integration.Features.Telephony;
using Sankore.Modules.Integration.Infrastructure;
using Sankore.Modules.Integration.PublicApi;
using Sankore.Shared.Kernel;

/// <summary>
/// The WhatsApp provider's inbound webhook (WA-BE-07): customers' messages and the delivery
/// statuses of ours.
///
/// <para>
/// ───────────────────────────────────────────────────────────────────────────────────────────<br/>
/// <b>HOST WIRING REQUIRED — <c>Program.cs</c>.</b> Mapped on the ROOT application, outside
/// <c>api/v1</c>, under <c>/integration/webhooks</c> — a prefix already exempt from FQDN tenant
/// resolution — and the host must declare the rate-limit policy named by
/// <see cref="RateLimitPolicy"/>: a policy named here and not declared there limits nothing.
/// </para>
/// <para>
/// ───────────────────────────────────────────────────────────────────────────────────────────
/// </para>
///
/// <para>
/// <b>The tenant comes from the phone-number id, never from a header</b> — the specification's
/// rule. The id is in the body, so it is the one thing read before verification, and it is read
/// by a forward-only scan that builds no object (<see cref="CloudApiWebhook.ReadPhoneNumberIds"/>).
/// It names one active connection globally, whose stored token then verifies the delivery; only a
/// verified body is stored, and only a stored body is parsed — by a job, later.
/// </para>
///
/// <para>
/// <b>How a delivery is verified.</b> 360dialog does not sign bodies with a secret the institution
/// holds, so the connection's webhook token — generated by this platform and handed to 360dialog
/// when the webhook is configured — comes back as the <c>X-Sankore-Webhook-Token</c> header and is
/// compared in constant time. A delivery carrying Meta's <c>X-Hub-Signature-256</c> is verified as
/// an HMAC over the body with the same secret instead, which is what a direct Meta connection would
/// send. Either proves the sender holds the secret; neither is optional.
/// </para>
///
/// <para>
/// <b>200 or 401, both with an empty body.</b> 200 because that is what Meta and 360dialog wait
/// for — anything else is redelivered for days. 401 for every refusal, unknown number included,
/// so the route says nothing about which institutions run WhatsApp. Answered in milliseconds: the
/// work is a Hangfire job that is handed the stored row's id and nothing else.
/// </para>
/// </summary>
internal static class MessagingWebhookEndpoints
{
    /// <summary>The named policy this route requires. A constant so the host and the route agree.</summary>
    internal const string RateLimitPolicy = "messaging-webhook";

    /// <summary>The header 360dialog is asked to echo the connection's token in.</summary>
    internal const string TokenHeader = "X-Sankore-Webhook-Token";

    /// <summary>Meta's own signature header, for a provider that signs.</summary>
    internal const string SignatureHeader = "X-Hub-Signature-256";

    /// <summary>
    /// 256 KB. A Cloud API delivery is a few kilobytes — media travel by id, never inline — so
    /// this bounds what an unauthenticated caller can make the endpoint buffer.
    /// </summary>
    private const int MaxBodyBytes = 256 * 1024;

    internal static IEndpointRouteBuilder MapMessagingWebhookEndpoints(this IEndpointRouteBuilder app)
    {
        ArgumentNullException.ThrowIfNull(app);

        app.MapPost("/integration/webhooks/whatsapp/{provider}", HandleAsync)
            .AllowAnonymous()
            .RequireRateLimiting(RateLimitPolicy)
            .WithName("WhatsAppWebhook")
            .WithTags("WhatsApp")
            .Produces(StatusCodes.Status200OK)
            .Produces(StatusCodes.Status401Unauthorized)
            .WithOpenApi();

        return app;
    }

    private static async Task<IResult> HandleAsync(
        string provider,
        HttpContext http,
        IntegrationDbContext db,
        MessagingChannels channels,
        TelephonyPayloadProtector payloads,
        ISecretsModule secrets,
        IBackgroundJobClient hangfire,
        TimeProvider clock,
        ILoggerFactory loggerFactory,
        CancellationToken ct)
    {
        var logger = loggerFactory.CreateLogger(typeof(MessagingWebhookEndpoints));
        var body = await ReadBodyAsync(http.Request.Body, ct);

        var accepted = body is not null && await AcceptAsync(
            provider,
            body,
            http.Request.Headers[TokenHeader].ToString(),
            http.Request.Headers[SignatureHeader].ToString(),
            db, channels, payloads, secrets, hangfire, clock, logger, ct);

        return accepted ? Results.Ok() : Results.Unauthorized();
    }

    /// <summary>
    /// Everything the endpoint decides, with no <c>HttpContext</c> — so the security properties
    /// can be pinned by a test, and so the development simulator runs the real path.
    /// </summary>
    internal static async Task<bool> AcceptAsync(
        string provider,
        byte[] body,
        string? token,
        string? signature,
        IntegrationDbContext db,
        MessagingChannels channels,
        TelephonyPayloadProtector payloads,
        ISecretsModule secrets,
        IBackgroundJobClient hangfire,
        TimeProvider clock,
        ILogger logger,
        CancellationToken ct)
    {
        ArgumentNullException.ThrowIfNull(body);

        var kind = KindOf(provider);

        if (kind is null)
        {
            logger.LogWarning("WhatsApp webhook refused: unknown provider segment.");
            return false;
        }

        // ONE number per delivery. Meta batches per number, so a body naming two is not a
        // delivery this platform sent anybody to make.
        var numbers = CloudApiWebhook.ReadPhoneNumberIds(body);

        if (numbers.Count != 1)
        {
            logger.LogWarning(
                "WhatsApp webhook refused: the body names {Count} phone-number ids.", numbers.Count);
            return false;
        }

        var connection = await channels.FindByAddressAsync(numbers[0], ct);

        if (connection is null || connection.Kind != kind)
        {
            // The id is not logged: it is the institution's, not a secret, but a log of refused
            // ids is a list of numbers somebody tried.
            logger.LogWarning("WhatsApp webhook refused: no active {Provider} number answers to this id.", kind);
            return false;
        }

        var tenantId = connection.TenantId;

        var secret = await secrets.GetValueAsync(
            IntegrationSecrets.WebhookSecretKey(tenantId, connection.Id), ct);

        if (string.IsNullOrWhiteSpace(secret))
        {
            // Fail closed: "no token configured" must never read as "no token required".
            logger.LogWarning(
                "WhatsApp webhook refused for connection {ConnectionId} of tenant {TenantId}: no "
                + "webhook token is configured — run « Configurer le webhook ».",
                connection.Id, tenantId);
            return false;
        }

        if (!Verify(secret, token, signature, body))
        {
            logger.LogWarning(
                "WhatsApp webhook refused for connection {ConnectionId} of tenant {TenantId}: "
                + "verification failed.", connection.Id, tenantId);
            return false;
        }

        // ── Verified. Stored as received, processed later. ───────────────
        var receivedAt = clock.GetUtcNow();
        var dedupKey = Convert.ToHexString(SHA256.HashData(body)).ToLowerInvariant();
        var connectionId = connection.Id;

        var alreadySeen = await db.MsgWebhookEvents
            .IgnoreQueryFilters()
            .AnyAsync(e => e.TenantId == tenantId && e.ConnectionId == connectionId && e.DedupKey == dedupKey, ct);

        if (alreadySeen)
        {
            logger.LogInformation(
                "WhatsApp webhook for connection {ConnectionId} is a redelivery; no work enqueued.", connectionId);
            return true;
        }

        var stored = MsgWebhookEvent.Receive(tenantId, connectionId, dedupKey, payloads.Protect(body), receivedAt);
        db.MsgWebhookEvents.Add(stored);

        try
        {
            await db.SaveChangesAsync(ct);
        }
        catch (DbUpdateException ex) when (
            (ex.InnerException?.Message ?? ex.Message).Contains("ux_msg_webhook_event_dedup", StringComparison.OrdinalIgnoreCase))
        {
            // A concurrent delivery of the same body won the insert: it does the work.
            return true;
        }

        // Hoisted: Hangfire serialises the argument expressions, and only identifiers reach the
        // queue — no body, no number, no header.
        var eventId = stored.Id;

        hangfire.Enqueue<ProcessMessagingWebhookJob>(job => job.ExecuteAsync(tenantId, connectionId, eventId));

        logger.LogInformation(
            "WhatsApp webhook accepted for connection {ConnectionId} of tenant {TenantId}; queued.",
            connectionId, tenantId);

        return true;
    }

    /// <summary>
    /// The token in constant time, or Meta's HMAC over the body. Hashing both sides first makes
    /// the comparison length-independent, so a wrong token's length leaks nothing either.
    /// </summary>
    internal static bool Verify(string secret, string? token, string? signature, byte[] body)
    {
        if (!string.IsNullOrWhiteSpace(signature)
            && signature.StartsWith("sha256=", StringComparison.OrdinalIgnoreCase))
        {
            var expected = HMACSHA256.HashData(Encoding.UTF8.GetBytes(secret), body);

            try
            {
                var given = Convert.FromHexString(signature["sha256=".Length..].Trim());

                if (CryptographicOperations.FixedTimeEquals(expected, given)) return true;
            }
            catch (FormatException)
            {
                // Not hex: fall through to the token, which may still be present.
            }
        }

        if (string.IsNullOrWhiteSpace(token)) return false;

        return CryptographicOperations.FixedTimeEquals(
            SHA256.HashData(Encoding.UTF8.GetBytes(token.Trim())),
            SHA256.HashData(Encoding.UTF8.GetBytes(secret.Trim())));
    }

    /// <summary>
    /// The provider segment of the route. <c>fake</c> is accepted for the development double, whose
    /// connections cannot exist outside Development.
    /// </summary>
    internal static IntegrationKind? KindOf(string? provider) => provider?.Trim().ToLowerInvariant() switch
    {
        "360dialog" or "dialog360" => IntegrationKind.Dialog360,
        "fake" => IntegrationKind.Fake,
        _ => null,
    };

    /// <summary>The route segment for a kind — what the webhook URL handed to the provider carries.</summary>
    internal static string SegmentOf(IntegrationKind kind) => kind switch
    {
        IntegrationKind.Dialog360 => "360dialog",
        _ => kind.ToString().ToLowerInvariant(),
    };

    private static async Task<byte[]?> ReadBodyAsync(Stream stream, CancellationToken ct)
    {
        using var buffer = new MemoryStream();

        var chunk = new byte[8 * 1024];
        int read;

        while ((read = await stream.ReadAsync(chunk, ct)) > 0)
        {
            if (buffer.Length + read > MaxBodyBytes) return null;

            await buffer.WriteAsync(chunk.AsMemory(0, read), ct);
        }

        return buffer.ToArray();
    }
}
